REVOKE CREATE ON SCHEMA public FROM PUBLIC;

CREATE ROLE shop_app
    LOGIN
    NOSUPERUSER
    NOCREATEDB
    NOCREATEROLE
    NOREPLICATION;

CREATE ROLE shop_read_1
    LOGIN
    NOSUPERUSER
    NOCREATEDB
    NOCREATEROLE
    NOREPLICATION;

CREATE ROLE shop_read_2
    LOGIN
    NOSUPERUSER
    NOCREATEDB
    NOCREATEROLE
    NOREPLICATION;

GRANT CONNECT ON DATABASE shop TO shop_app;
GRANT CONNECT ON DATABASE shop TO shop_read_1;
GRANT CONNECT ON DATABASE shop TO shop_read_2;

GRANT USAGE ON SCHEMA public TO shop_app;
GRANT USAGE ON SCHEMA public TO shop_read_1;
GRANT USAGE ON SCHEMA public TO shop_read_2;

GRANT SELECT, INSERT, UPDATE, DELETE
    ON ALL TABLES IN SCHEMA public
    TO shop_app;

GRANT USAGE, SELECT
    ON ALL SEQUENCES IN SCHEMA public
    TO shop_app;

GRANT SELECT
    ON ALL TABLES IN SCHEMA public
    TO shop_read_1, shop_read_2;

GRANT SELECT
    ON ALL SEQUENCES IN SCHEMA public
    TO shop_read_1, shop_read_2;
